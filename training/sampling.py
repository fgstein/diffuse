# Proposed EDM sampler (Algorithm 2), with CFG.

def lowpass(x, factor):
    """Low-pass filter used by ILVR: average-pool by `factor`, then bilinear upsampling."""
    if factor <= 1:
        return x
    H, W = x.shape[-2:]
    if H % factor or W % factor:
        raise ValueError(f'ILVR factor {factor} must divide the image size {H}x{W}')
    y = torch.nn.functional.avg_pool2d(x, factor)
    return torch.nn.functional.interpolate(y, size=(H, W), mode='bilinear', align_corners=False)

def edm_sampler(
    net, latents, cond=None, randn_like=torch.randn_like,
    num_steps=18, sigma_min=0.002, sigma_max=80, rho=7,
    S_churn=0, S_min=0, S_max=float('inf'), S_noise=1,
    guidance=1.0, guidance_interval=None,
    x_init=None, sigma_start=None,
    ilvr_ref=None, ilvr_factor=0, ilvr_sigma_min=0.0,
):
    """EDM Heun sampler.

    Image-to-image (SDEdit, Meng et al. 2021): with `x_init` (images in [-1, 1]) and
    `sigma_start`, sampling starts from x_init + sigma_start * latents and integrates
    from sigma_start down to 0 (`num_steps` steps over that shorter range). Detail
    below the scale ~sigma_start is regenerated by the model; coarser content is kept.

    ILVR (Choi et al. 2021): with `ilvr_ref` (images in [-1, 1]) and `ilvr_factor` N > 1,
    after every step whose target noise level t_next >= max(ilvr_sigma_min, >0), the
    low-pass part of x is replaced by that of the noised reference:
        x <- x - LP_N(x) + LP_N(ilvr_ref + t_next * eps)
    so frequencies below ~1/N follow the reference and only finer detail is generated.
    The final step (t_next = 0) is left free to avoid filter artifacts.
    """
    # Canonicalize the condition dict once (also accepts legacy label tensors / None).
    cond = net.cond_stack.normalize(cond, n=latents.shape[0], device=latents.device)
    null_cond = net.null_cond(latents.shape[0], latents.device)
    denoise = lambda x, t: guided_denoise(net, x, t, cond, guidance=guidance,
        guidance_interval=guidance_interval, null_cond=null_cond).to(torch.float64)

    # Image-to-image: start from a noised input image at sigma_start.
    if x_init is not None:
        if sigma_start is None:
            raise ValueError('x_init requires sigma_start')
        sigma_max = float(sigma_start)
        if sigma_max <= sigma_min:
            raise ValueError(f'sigma_start ({sigma_max}) must be > sigma_min ({sigma_min})')
    use_ilvr = (ilvr_ref is not None) and (ilvr_factor or 0) > 1
    if use_ilvr:
        ilvr_ref = ilvr_ref.to(torch.float64)
        lowpass(ilvr_ref[:1], ilvr_factor) # validate the factor early

    # Adjust noise levels based on what's supported by the network.
    sigma_min = max(sigma_min, net.sigma_min)
    sigma_max = min(sigma_max, net.sigma_max)

    # Time step discretization.
    step_indices = torch.arange(num_steps, dtype=torch.float64, device=latents.device)
    t_steps = (sigma_max ** (1 / rho) + step_indices / (num_steps - 1) * (sigma_min ** (1 / rho) - sigma_max ** (1 / rho))) ** rho
    t_steps = torch.cat([net.round_sigma(t_steps), torch.zeros_like(t_steps[:1])]) # t_N = 0

    # Main sampling loop.
    x_next = latents.to(torch.float64) * t_steps[0]
    if x_init is not None:
        x_next = x_next + x_init.to(torch.float64)
    for i, (t_cur, t_next) in enumerate(zip(t_steps[:-1], t_steps[1:])): # 0, ..., N-1
        x_cur = x_next

        # Increase noise temporarily.
        gamma = min(S_churn / num_steps, np.sqrt(2) - 1) if S_min <= t_cur <= S_max else 0
        t_hat = net.round_sigma(t_cur + gamma * t_cur)
        x_hat = x_cur + (t_hat ** 2 - t_cur ** 2).sqrt() * S_noise * randn_like(x_cur)

        # Euler step.
        denoised = denoise(x_hat, t_hat)
        d_cur = (x_hat - denoised) / t_hat
        x_next = x_hat + (t_next - t_hat) * d_cur

        # Apply 2nd order correction.
        if i < num_steps - 1:
            denoised = denoise(x_next, t_next)
            d_prime = (x_next - denoised) / t_next
            x_next = x_hat + (t_next - t_hat) * (0.5 * d_cur + 0.5 * d_prime)

        # ILVR: impose the low frequencies of the (noised) reference.
        if use_ilvr and t_next > 0 and t_next >= ilvr_sigma_min:
            ref_t = ilvr_ref + t_next * randn_like(x_next)
            x_next = x_next - lowpass(x_next, ilvr_factor) + lowpass(ref_t, ilvr_factor)

    return x_next

#----------------------------------------------------------------------------
# Convenience: generate images for explicit (seed, class index) pairs.

@torch.no_grad()
def generate(net, seeds, class_indices, device, guidance=1.0, num_steps=32, sigma_max=80.0,
             sigma_min=0.002, rho=7, batch_size=64, guidance_interval=None, **sampler_kwargs):
    """Returns uint8 images [N, C, H, W] (CPU). class_indices may be None (unconditional)."""
    out = []
    for start in range(0, len(seeds), batch_size):
        bseeds = seeds[start:start + batch_size]
        rnd = StackedRandomGenerator(device, bseeds)
        latents = rnd.randn([len(bseeds), net.img_channels, net.img_resolution, net.img_resolution], device=device)
        cond = None
        if class_indices is not None and 'class' in net.cond_stack.names:
            cond = {'class': torch.as_tensor(class_indices[start:start + batch_size], dtype=torch.int64, device=device)}
        x = edm_sampler(net, latents, cond, randn_like=rnd.randn_like, num_steps=num_steps,
            sigma_min=sigma_min, sigma_max=sigma_max, rho=rho, guidance=guidance,
            guidance_interval=guidance_interval, **sampler_kwargs)
        out.append(to_uint8(x).cpu())
    return torch.cat(out)

def to_uint8(x):
    return (x * 127.5 + 128).clip(0, 255).to(torch.uint8)

