"""Regenerate docs/cli-reference.md from the click definitions of the CLIs.

    uv run python tools/gen_cli_reference.py
"""

import os
import sys
import importlib
import click

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, REPO)

SCRIPTS = [
    ('train.py', 'train', 'main'),
    ('generate.py', 'generate', 'main'),
    ('tools/prepare_dataset.py', 'tools.prepare_dataset', 'main'),
    ('tools/make_synthetic_dataset.py', 'tools.make_synthetic_dataset', 'main'),
    ('tools/plot_stats.py', 'tools.plot_stats', 'main'),
    ('tools/memorization_check.py', 'tools.memorization_check', 'main'),
    ('tools/translate.py', 'tools.translate', 'main'),
    ('tools/style_mosaic.py', 'tools.style_mosaic', 'main'),
    ('tools/domain_gap.py', 'tools.domain_gap', 'main'),
]

def _default(p):
    if p.is_flag:
        return 'flag'
    d = p.default
    if callable(d) or d is None or 'Sentinel' in type(d).__name__ or 'UNSET' in str(d):
        return ''
    if isinstance(d, (list, tuple)):
        d = ','.join(str(x) for x in d)
    return f'`{d}`'

def _type(p):
    if isinstance(p.type, click.Choice):
        return ' \\| '.join(p.type.choices)
    return (p.metavar or p.type.name.upper()).replace('|', '\\|')

def render(script, cmd):
    lines = [f'## `{script}`', '']
    doc = (cmd.help or '').split('\n\n')[0].replace('\n', ' ').strip()
    if doc:
        lines += [doc, '']
    lines += ['| Option | Type | Default | Description |', '|---|---|---|---|']
    for p in cmd.params:
        if isinstance(p, click.Argument):
            lines.append(f'| `{p.name.upper()}` (argument) | path | | required |')
            continue
        names = ', '.join(f'`{o}`' for o in p.opts)
        help_ = (p.help or '').replace('|', '\\|')
        if p.required:
            help_ = '**required.** ' + help_
        lines.append(f'| {names} | {_type(p)} | {_default(p)} | {help_} |')
    return '\n'.join(lines) + '\n'

def main():
    out = ['# CLI reference', '',
           '> Generated by `tools/gen_cli_reference.py` from the code. Do not edit by hand.', '',
           'Boolean options take `0/1`, `true/false` or `yes/no`. List options take comma-separated values (`1,2,2`); '
           'integer lists also accept ranges (`0-63`).', '']
    for script, module, attr in SCRIPTS:
        cmd = getattr(importlib.import_module(module), attr)
        out.append(render(script, cmd))
    path = os.path.join(REPO, 'docs', 'cli-reference.md')
    with open(path, 'wt') as f:
        f.write('\n'.join(out))
    print(f'Wrote {path}')

if __name__ == '__main__':
    main()
